    val onSurfaceVariant: Color,
    val surfaceBorder: Color,
    val accentGlow: Color,
    val codeBackground: Color,
    val terminalPrompt: Color,
    val agentBadgeColor: Color,
    val isDark: Boolean = true,
    val id: String = letter.toString(),
    val badgeCode: String = letter.toString(),
    val category: ThemeCategory = ThemeCategory.ATMOSPHERIC
)

