/**
 * Complete Multi-Theme Definitions for ChatOS
 * Includes the flagship Obsidian Crimson theme, Obsidian & Red variants,
 * Luxury Dark, Cyber & Neon, Atmospheric, Terminal, and all 26 A–Z Themes.
 */
enum class ThemeMaterialStyle {
    GLASSMORPHIC,
    BRUTALIST_CONCRETE,
    NEON_GLOW,
    WARM_ORGANIC,
    METALLIC_CHROME,
    RETRO_CRT,
    VELVET_LUXURY,
    MINIMAL_TITANIUM,
    HOLOGRAPHIC,
    TERMINAL_PHOSPHOR
}

enum class ThemeCategory(val label: String) {
    ALL("All"),
    OBSIDIAN_RED("Obsidian & Red"),
    LUXURY_DARK("Luxury Dark"),
    CYBER_NEON("Cyber & Neon"),
    ATMOSPHERIC("Atmospheric"),
    TERMINAL("Terminal & Mono")
}

data class ChatOSTheme(
    val letter: Char,
    val name: String,
    val tagLine: String,
    val emotionalTone: String,
    val materialStyle: ThemeMaterialStyle,
    val primary: Color,
    val onPrimary: Color,
